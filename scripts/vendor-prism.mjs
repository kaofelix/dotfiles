#!/usr/bin/env node
// Builds changes-panel's vendor/prism.js: Prism's core and the languages below, in dependency
// order, as one ES module. Herdr mods run in QuickJS and import only their own relative files,
// so Prism is vendored rather than installed.
//
//   npm pack prismjs@<version> && tar xzf prismjs-<version>.tgz
//   node scripts/vendor-prism.mjs package
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const LANGUAGES = `
  javascript typescript jsx tsx rust go c cpp csharp java kotlin swift scala dart php zig protobuf
  python bash ruby perl r yaml toml ini json json5 css scss less sql graphql markup markdown
  lisp clojure scheme lua nix docker makefile haskell elixir erlang ocaml hcl powershell diff
`.split(/\s+/).filter(Boolean);

const source = process.argv[2];
if (!source || process.argv.includes("--help")) {
  console.log("usage: node scripts/vendor-prism.mjs <unpacked prismjs package folder>");
  process.exit(source ? 0 : 1);
}
const pkg = JSON.parse(readFileSync(join(source, "package.json"), "utf8"));
const components = JSON.parse(readFileSync(join(source, "components.json"), "utf8")).languages;
const list = (v) => (v == null ? [] : Array.isArray(v) ? v : [v]);

// Each language after what it requires, and after optional ones that are also included.
const wanted = new Set();
const want = (id) => {
  if (wanted.has(id)) return;
  if (!components[id]) throw new Error(`no Prism language ${id}`);
  list(components[id].require).forEach(want);
  wanted.add(id);
};
LANGUAGES.forEach(want);
const order = [];
const place = (id) => {
  if (order.includes(id)) return;
  [...list(components[id].require), ...list(components[id].optional).filter((o) => wanted.has(o))].forEach(place);
  order.push(id);
};
[...wanted].forEach(place);

const read = (name) => readFileSync(join(source, "components", `prism-${name}.js`), "utf8").trim();
const license = readFileSync(join(source, "LICENSE"), "utf8").trim().replace(/^/gm, " * ");
const out = `// Generated by scripts/vendor-prism.mjs from prismjs ${pkg.version}. Do not edit.
// Languages: ${order.join(" ")}
/*
${license}
 */

// The core, kept off the global object and out of module.exports.
const Prism = (() => {
  const module = undefined, global = undefined;
  ${read("core").replace(/\n/g, "\n  ")}
  Prism.manual = true;
  return Prism;
})();

${order.map((id) => `// ${id}\n${read(id)}`).join("\n\n")}

export default Prism;
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../home/dot_config/herdr-app/mods/changes-panel/vendor/prism.js");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`wrote ${target}: ${order.length} languages, ${(out.length / 1024).toFixed(0)} KiB`);
